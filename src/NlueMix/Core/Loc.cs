using System.Collections.Generic;

namespace NlueMix.Core;

/// <summary>
/// 界面多语言。
///
/// 为什么用代码里的字典、而不是 .resx 资源文件：
///   .resx 要配 SatelliteResourceLanguages、每种语言一个文件、改一条文案要动 N 个文件；
///   这个项目的界面字符串不多（几十条），集中在一个字典里更好维护，
///   也方便开源贡献者直接对照着加语言 —— 改一个文件就能提 PR。
///
/// 覆盖范围说明（重要）：
///   翻译的是【用户看得见的界面文案】。
///   诊断日志、异常堆栈、开发者版才显示的技术细节【保持中文】——
///   它们面向的是排查问题的人，混进八种语言反而没法搜、没法对照。
/// </summary>
public static class Loc
{
    /// <summary>支持的语言。顺序就是界面下拉里的顺序。</summary>
    public static readonly (string Code, string NativeName)[] Languages =
    {
        ("zh-CN", "简体中文"),
        ("en",    "English"),
        ("ja",    "日本語"),
        ("ko",    "한국어"),
        ("de",    "Deutsch"),
        ("fr",    "Français"),
        ("es",    "Español"),
        ("ru",    "Русский"),
    };

    private static string _code = "zh-CN";

    public static string CurrentCode => _code;

    /// <summary>切换语言。无效代码回落到简体中文。</summary>
    public static void SetLanguage(string code)
    {
        foreach (var (c, _) in Languages)
        {
            if (c == code) { _code = code; return; }
        }
        _code = "zh-CN";
    }

    /// <summary>取一句话。找不到的 key 返回 key 本身，方便一眼看出漏翻。</summary>
    public static string T(string key)
    {
        if (Table.TryGetValue(_code, out var map) && map.TryGetValue(key, out var v)) return v;
        if (Table.TryGetValue("en", out var en) && en.TryGetValue(key, out var ev)) return ev;
        if (Table.TryGetValue("zh-CN", out var zh) && zh.TryGetValue(key, out var zv)) return zv;
        return key;
    }

    /// <summary>带参数取句（用 {0} {1} 占位）。</summary>
    public static string T(string key, params object[] args)
    {
        try { return string.Format(T(key), args); }
        catch { return T(key); }
    }

